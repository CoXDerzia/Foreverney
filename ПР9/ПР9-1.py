print("программа выводит числа от 1 до n включительно за исключением: чисел от 5 до 9; от 17 до 37; от 78 до 87.")

n = int(input("Введите натуральное число: "))

i = 1
while i <= n:
    if (5 <= i <= 9) or (17 <= i <= 37) or (78 <= i <= 87):
        i += 1
        continue
    print(i)
    i += 1